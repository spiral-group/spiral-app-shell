// @vitest-environment happy-dom

/*
Copyright 2026 the Spiral authors. AGPL-3.0-or-later.

Brief 0066. The two things the ruler could not see.

happy-dom does not lay out — every rect it returns is zero — so this cannot
test the ruler against real layout, and does not pretend to. What it pins is
the part that is arithmetic: the thresholds, and the exclusions that keep a
check from crying wolf. The rects are supplied.

Both checks exist because of one screen. A post generated by production
opened full screen with its canvas collapsed to a sliver and its colour
palette lying across the Clear button, and `measureLayout` reported `ok`.
The canvas was invisible to it for an exact reason: a collapsed element has
zero height, `isVisible` drops it, and every later check iterates the
survivors. The blind spot was in the filter, not in the checks.
*/

import { beforeEach, describe, expect, it } from "vitest";

import { measureLayout } from "./measure";

type Box = { x: number; y: number; width: number; height: number };

/** Give an element the rect it would have if anything here laid out. */
const place = (el: Element, box: Box): void => {
  el.getBoundingClientRect = () =>
    ({
      x: box.x,
      y: box.y,
      left: box.x,
      top: box.y,
      right: box.x + box.width,
      bottom: box.y + box.height,
      width: box.width,
      height: box.height,
      toJSON: () => ({}),
    }) as DOMRect;
};

let root: HTMLElement;

beforeEach(() => {
  document.body.innerHTML = "";
  root = document.createElement("div");
  document.body.append(root);
  place(root, { x: 0, y: 0, width: 402, height: 758 });
});

const codes = (mode: "row" | "expanded" = "expanded"): string[] =>
  measureLayout(root, mode).problems.map((p) => p.code);

describe("a drawing surface that is not one", () => {
  it("reports a canvas that collapsed to a sliver", () => {
    const canvas = document.createElement("canvas");
    root.append(canvas);
    place(canvas, { x: 0, y: 0, width: 402, height: 6 });

    expect(codes()).toContain("collapsed");
  });

  it("sees it even though a collapsed element counts as invisible", () => {
    // The exact shape of the miss: height zero. Every other check in the
    // ruler iterates `isVisible` survivors, so this one has to run first.
    const canvas = document.createElement("canvas");
    root.append(canvas);
    place(canvas, { x: 0, y: 0, width: 402, height: 0 });

    expect(codes()).toContain("collapsed");
  });

  it("says nothing about a canvas with room to draw on", () => {
    const canvas = document.createElement("canvas");
    root.append(canvas);
    place(canvas, { x: 0, y: 0, width: 402, height: 500 });

    expect(codes()).not.toContain("collapsed");
  });

  it("leaves a deliberately hidden canvas alone", () => {
    const canvas = document.createElement("canvas");
    canvas.style.display = "none";
    root.append(canvas);
    place(canvas, { x: 0, y: 0, width: 0, height: 0 });

    expect(codes()).not.toContain("collapsed");
  });
});

describe("one control on top of another", () => {
  const button = (label: string, box: Box): HTMLButtonElement => {
    const el = document.createElement("button");
    el.textContent = label;
    root.append(el);
    place(el, box);
    return el;
  };

  it("reports two controls sharing the same pixels", () => {
    button("Очистити", { x: 200, y: 100, width: 120, height: 44 });
    button("Червоний", { x: 260, y: 110, width: 44, height: 44 });

    expect(codes()).toContain("overlap");
  });

  it("allows controls that merely touch", () => {
    button("Тонкий", { x: 0, y: 100, width: 100, height: 44 });
    button("Товстий", { x: 100, y: 100, width: 100, height: 44 });

    expect(codes()).not.toContain("overlap");
  });

  it("does not count a control nested inside another", () => {
    const outer = button("Картка", { x: 0, y: 0, width: 300, height: 200 });
    const inner = document.createElement("button");
    inner.textContent = "Всередині";
    outer.append(inner);
    place(inner, { x: 20, y: 20, width: 100, height: 44 });

    expect(codes()).not.toContain("overlap");
  });
});

describe("a control cut off at the side by a card", () => {
  // The phone case (2026-09-22): a scoreboard's row, too wide for its card
  // because «Alice Example» would not wrap, put «+1» past the card's edge.
  // The card hides overflow, so the button stayed inside the BOX and the
  // document's scroll width never grew: every check passed.
  const card = (overflowX: string, box: Box): HTMLElement => {
    const el = document.createElement("div");
    el.style.overflowX = overflowX;
    root.append(el);
    place(el, box);
    return el;
  };
  const plusOne = (parent: HTMLElement, box: Box): void => {
    const el = document.createElement("button");
    el.textContent = "+1";
    parent.append(el);
    place(el, box);
  };

  it("reports a control past the edge of a card that hides overflow", () => {
    const c = card("hidden", { x: 12, y: 12, width: 298, height: 200 });
    plusOne(c, { x: 290, y: 60, width: 44, height: 44 });

    expect(codes("row")).toContain("clipped");
    expect(codes("expanded")).toContain("clipped");
  });

  it("leaves a control inside its card alone", () => {
    const c = card("hidden", { x: 12, y: 12, width: 298, height: 200 });
    plusOne(c, { x: 250, y: 60, width: 44, height: 44 });

    expect(codes("row")).not.toContain("clipped");
  });

  it("does not count a scroller: what it hides can be reached", () => {
    const c = card("auto", { x: 12, y: 12, width: 298, height: 200 });
    plusOne(c, { x: 290, y: 60, width: 44, height: 44 });

    expect(codes("expanded")).not.toContain("clipped");
  });
});

describe("a text squeezed below its words", () => {
  // happy-dom does not lay out, so the widths are supplied. The phone case
  // (§ 5.58): a centred caption crushed to zero width beside a group that
  // took the line — and zero width is what `isVisible` drops, so the check
  // must read every element, not the visible ones.
  const text = (words: string, client: number, scroll: number, overflow = "visible"): void => {
    const el = document.createElement("p");
    el.textContent = words;
    el.style.overflowX = overflow;
    root.append(el);
    place(el, { x: 0, y: 0, width: client, height: client === 0 ? 0 : 20 });
    Object.defineProperty(el, "clientWidth", { value: client });
    Object.defineProperty(el, "scrollWidth", { value: scroll });
  };

  it("reports a caption with no width left for its words", () => {
    text("Привітань: 0", 0, 58);
    expect(codes("row")).toContain("squeezed");
  });

  it("reports one narrower than its longest word", () => {
    text("Записатись", 73, 81);
    expect(codes("row")).toContain("squeezed");
  });

  it("leaves an ellipsis alone — it clips on purpose", () => {
    text("Олександра Коваленко-Петренко", 60, 200, "hidden");
    expect(codes("row")).not.toContain("squeezed");
  });

  it("leaves text that fits alone", () => {
    text("Вітаємо", 100, 90);
    expect(codes("row")).not.toContain("squeezed");
  });
});
